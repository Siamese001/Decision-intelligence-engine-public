"""Roster & charter set-difference reconciler for detecting roll-offs.

Compares active graph workstream memberships against newly ingested rosters
and status tables to identify silent personnel roll-offs via negative evidence.
"""

from __future__ import annotations

import uuid
from dataclasses import asdict, dataclass
from datetime import date
from pathlib import Path
from typing import Any, Dict, List, Optional, Set

from storage.connection import create_sqlite_conn

COMPREHENSIVE_SOURCE_TYPES: set[str] = {
    "ROSTER",
    "CHARTER_ROSTER",
    "STATUS_PACKET_TABLE",
    "ORG_CHART",
    "SOW_DELIVERY_TEAM",
}


@dataclass(frozen=True)
class RoleRetractionCandidate:
    """Structured retraction proposal generated from roster omission."""

    candidate_id: str
    target_edge_id: str
    missing_entity_id: str
    missing_entity_name: str
    workstream_node_id: str
    workstream_name: str
    edge_type: str
    prior_source_id: str
    prior_source_date: str
    retracting_source_id: str
    retracting_source_name: str
    retracting_source_date: str
    confidence_score: float
    retraction_reason: str
    status: str = "PENDING_REVIEW"

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class SetDiffReconciliationReport:
    """Report generated by a roster set-difference comparison."""

    workstream_node_id: str
    retracting_source_id: str
    source_type: str
    is_comprehensive: bool
    active_graph_members: List[str]
    new_source_members: List[str]
    omitted_members: List[str]
    candidates: List[RoleRetractionCandidate]
    disqualification_reason: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "workstream_node_id": self.workstream_node_id,
            "retracting_source_id": self.retracting_source_id,
            "source_type": self.source_type,
            "is_comprehensive": self.is_comprehensive,
            "active_graph_members": self.active_graph_members,
            "new_source_members": self.new_source_members,
            "omitted_members": self.omitted_members,
            "candidates": [c.to_dict() for c in self.candidates],
            "disqualification_reason": self.disqualification_reason,
        }


class SetDiffReconciler:
    """Reconciles new team rosters against current knowledge graph workstream edges."""

    def __init__(self, db_path: Path | str) -> None:
        raw_p = Path(db_path) if isinstance(db_path, str) else db_path
        self.db_path = raw_p.resolve()

    def _resolve_node_name_expr(self, conn: Any, table_alias: str, fallback_col: str) -> str:
        cur = conn.cursor()
        cur.execute("PRAGMA table_info(node);")
        cols = {row[1] for row in cur.fetchall()}
        candidates: list[str] = []
        for col in ("canonical_name", "display_name", "name", "label"):
            if col in cols:
                candidates.append(f"{table_alias}.{col}")
        candidates.append(fallback_col)
        return f"COALESCE({', '.join(candidates)})"

    def _resolve_active_workstream_edges(self, conn: Any, workstream_id: str) -> List[Dict[str, Any]]:
        from_expr = self._resolve_node_name_expr(conn, "fn", "e.from_node_id")
        to_expr = self._resolve_node_name_expr(conn, "tn", "e.to_node_id")
        query = f"""
            SELECT
                e.edge_id,
                e.from_node_id,
                {from_expr} AS from_name,
                e.edge_type,
                e.to_node_id,
                {to_expr} AS to_name,
                e.source_id,
                COALESCE(s.source_date, substr(e.created_at, 1, 10)) AS source_date
            FROM edge e
            LEFT JOIN node fn ON e.from_node_id = fn.node_id
            LEFT JOIN node tn ON e.to_node_id = tn.node_id
            LEFT JOIN source s ON e.source_id = s.source_id
            WHERE e.superseded_by IS NULL
              AND e.to_node_id = ?
              AND e.edge_type IN ('OWNS_OR_LEADS', 'DATED_ROLE_IN', 'CONTRIBUTES_TO', 'ROSTER_ROW_IN')
        """
        cur = conn.cursor()
        cur.execute(query, (workstream_id,))
        return [dict(row) for row in cur.fetchall()]

    def reconcile_roster(
        self,
        workstream_id: str,
        new_source_id: str,
        source_type: str,
        source_name: str,
        source_date: str,
        roster_member_node_ids: Sequence[str],
    ) -> SetDiffReconciliationReport:
        norm_type = source_type.strip().upper()
        is_comprehensive = norm_type in COMPREHENSIVE_SOURCE_TYPES
        clean_new_members = sorted(set(roster_member_node_ids))

        if not is_comprehensive:
            return SetDiffReconciliationReport(
                workstream_node_id=workstream_id,
                retracting_source_id=new_source_id,
                source_type=norm_type,
                is_comprehensive=False,
                active_graph_members=[],
                new_source_members=clean_new_members,
                omitted_members=[],
                candidates=[],
                disqualification_reason=f"SOURCE_TYPE_NON_COMPREHENSIVE: '{norm_type}' cannot prove omission",
            )

        if not clean_new_members:
            return SetDiffReconciliationReport(
                workstream_node_id=workstream_id,
                retracting_source_id=new_source_id,
                source_type=norm_type,
                is_comprehensive=True,
                active_graph_members=[],
                new_source_members=[],
                omitted_members=[],
                candidates=[],
                disqualification_reason="EMPTY_ROSTER_PAYLOAD: Roster must contain at least one valid member",
            )

        conn = create_sqlite_conn(self.db_path, readonly=True)
        try:
            active_edges = self._resolve_active_workstream_edges(conn, workstream_id)
        finally:
            conn.close()

        active_members_map: Dict[str, List[Dict[str, Any]]] = {}
        for edge in active_edges:
            mid = edge["from_node_id"]
            active_members_map.setdefault(mid, []).append(edge)

        active_member_ids = set(active_members_map.keys())
        omitted_ids = sorted(active_member_ids - set(clean_new_members))

        candidates: List[RoleRetractionCandidate] = []
        for mid in omitted_ids:
            edges = active_members_map[mid]
            for e in edges:
                cand_id = f"retract_{uuid.uuid4().hex[:12]}"
                candidates.append(
                    RoleRetractionCandidate(
                        candidate_id=cand_id,
                        target_edge_id=e["edge_id"],
                        missing_entity_id=mid,
                        missing_entity_name=e["from_name"],
                        workstream_node_id=workstream_id,
                        workstream_name=e["to_name"],
                        edge_type=e["edge_type"],
                        prior_source_id=e["source_id"],
                        prior_source_date=e["source_date"],
                        retracting_source_id=new_source_id,
                        retracting_source_name=source_name,
                        retracting_source_date=source_date,
                        confidence_score=0.95,
                        retraction_reason=f"OMITTED_FROM_COMPREHENSIVE_ROSTER: Dropped in {new_source_id}",
                    )
                )

        return SetDiffReconciliationReport(
            workstream_node_id=workstream_id,
            retracting_source_id=new_source_id,
            source_type=norm_type,
            is_comprehensive=True,
            active_graph_members=sorted(active_member_ids),
            new_source_members=clean_new_members,
            omitted_members=omitted_ids,
            candidates=candidates,
        )
