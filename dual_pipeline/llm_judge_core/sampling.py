"""
dual_pipeline/llm_judge_core/sampling.py

Judge Reliability Controls (Wave 4):
1. N-sample median evaluation with spread gating (spread > 5.0 pts triggers HITL).
2. Self-evaluation prevention (Decision D1: judge must never be the generator model).
3. Provenance attachment and sample spread metrics.
"""
from __future__ import annotations

import logging
import statistics
from typing import Any, Callable, Dict, List, Optional, Sequence

logger = logging.getLogger(__name__)

DEFAULT_SAMPLE_COUNT: int = 3
MAX_ALLOWED_SPREAD: float = 5.0


def _extract_model_family(model_name: str) -> str:
    """Extract model family prefix (e.g. gpt, claude, gemini, qwen, llama)."""
    norm = model_name.strip().lower()
    if any(k in norm for k in ("gpt", "openai", "astra", "luna", "sol", "terra")):
        return "openai_gpt"
    if any(k in norm for k in ("claude", "anthropic")):
        return "anthropic_claude"
    if any(k in norm for k in ("gemini", "google")):
        return "google_gemini"
    if any(k in norm for k in ("qwen", "alibaba")):
        return "qwen"
    if any(k in norm for k in ("llama", "meta")):
        return "meta_llama"
    return norm.split("-")[0] if "-" in norm else norm


def check_self_evaluation(judge_model: str, metadata: Optional[Dict[str, Any]]) -> Optional[str]:
    """Decision D1 & Wave 3: Judge must never evaluate output from same model or model family.
    
    Fails closed when generator_model provenance is missing in production.
    """
    from storage.credentials import CredentialManager
    if not metadata or not isinstance(metadata, dict):
        metadata = {}

    env_val = str(metadata.get("environment") or metadata.get("ENVIRONMENT") or "").strip().lower()
    is_production = (
        env_val == "production"
        or metadata.get("require_provenance") is True
        or metadata.get("REQUIRE_PROVENANCE") is True
        or metadata.get("is_production") is True
        or CredentialManager.get_env("PRODUCTION_MODE") == "1"
    )

    generator = (
        metadata.get("generator_model")
        or metadata.get("producer_model")
        or metadata.get("generating_model")
        or metadata.get("producer")
        or metadata.get("model")
    )

    if not generator or not isinstance(generator, str):
        if is_production:
            return (
                "FAIL CLOSED: Missing generator_model provenance is required in production "
                "to verify cross-family judge independence."
            )
        return None

    j_norm = judge_model.strip().lower()
    g_norm = generator.strip().lower()

    if j_norm == g_norm or (len(j_norm) > 4 and j_norm in g_norm) or (len(g_norm) > 4 and g_norm in j_norm):
        return (
            f"SELF-EVALUATION REJECTED (Decision D1): Judge model '{judge_model}' cannot evaluate "
            f"output generated by the same model '{generator}'. Re-route to an independent judge model."
        )

    # Cross-family check
    j_fam = _extract_model_family(judge_model)
    g_fam = _extract_model_family(generator)
    if j_fam and g_fam and j_fam == g_fam and j_fam != "mock":
        return (
            f"CROSS-FAMILY SELF-EVALUATION BIAS REJECTED: Judge model '{judge_model}' and generator "
            f"model '{generator}' share the same model family ('{j_fam}'). "
            "Cross-family evaluation is required to eliminate intra-family sycophancy bias."
        )

    return None


def evaluate_sampled_judge(
    judge_fn: Optional[Callable[[], Dict[str, Any]]] = None,
    n_samples: int = DEFAULT_SAMPLE_COUNT,
    max_spread: float = MAX_ALLOWED_SPREAD,
    sample_cards: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """Evaluate N independent samples, compute median scorecard, and enforce spread gate.
    
    If spread = max(scores) - min(scores) > max_spread (5.0 pts):
        Routes verdict and status to HITL_REQUIRED.
    Otherwise:
        Selects median scorecard and attaches multi-sample telemetry.
    """
    cards: List[Dict[str, Any]] = []

    if sample_cards is not None:
        cards = list(sample_cards)
    elif judge_fn is not None:
        for i in range(max(1, n_samples)):
            try:
                card = judge_fn()
                cards.append(card)
            except Exception as exc:
                logger.error("Error drawing judge sample %d/%d: %s", i + 1, n_samples, exc)
                return {
                    "status": "HITL_REQUIRED",
                    "verdict": "HITL_REQUIRED",
                    "composite_score": None,
                    "is_fallback": True,
                    "forensic_rationale": f"JUDGE INVOCATION FAILURE on sample {i + 1}/{n_samples}: {exc}. Routed to HITL.",
                    "defect_codes": ["ERR_JUDGE_INVOCATION_FAILURE"],
                    "sample_count": len(cards),
                }

    if not cards:
        return {
            "status": "FAIL",
            "verdict": "FAIL",
            "composite_score": 0,
            "forensic_rationale": "No judge evaluation samples produced.",
            "defect_codes": ["ERR_NO_SAMPLES"],
            "sample_count": 0,
        }

    # If any sample hit a provider 429 or requested HITL, route to HITL immediately
    for card in cards:
        if card.get("verdict") == "HITL_REQUIRED" or card.get("status") == "HITL_REQUIRED":
            hitl_result = dict(card)
            hitl_result["sample_count"] = len(cards)
            return hitl_result

    scores: List[float] = []
    valid_scored_cards: List[Dict[str, Any]] = []
    for card in cards:
        sc = card.get("composite_score")
        if sc is not None and isinstance(sc, (int, float)):
            scores.append(float(sc))
            valid_scored_cards.append(card)

    if not scores:
        return cards[0]

    spread = max(scores) - min(scores)
    median_score = round(float(statistics.median(scores)), 2)

    # Pick the card closest to the median score
    closest_card = min(valid_scored_cards, key=lambda c: abs(float(c.get("composite_score", 0)) - median_score))
    result = dict(closest_card)
    result["composite_score"] = median_score
    result["sample_count"] = len(cards)
    result["sample_spread"] = round(spread, 2)
    result["sample_scores"] = scores
    result["is_fallback"] = any(bool(c.get("is_fallback", False)) for c in cards)

    # Check spread gate
    if spread > max_spread:
        logger.warning(
            "Judge reliability spread failure: spread %.2f > max %.2f across %d samples (%s)",
            spread, max_spread, len(cards), scores,
        )
        result["verdict"] = "HITL_REQUIRED"
        result["status"] = "HITL_REQUIRED"
        existing_rat = result.get("forensic_rationale", "")
        spread_msg = (
            f"JUDGE SPREAD EXCEEDED ({spread:.1f} > {max_spread:.1f} pts): Across {len(cards)} samples, "
            f"scores were {scores} (median={median_score}). High variance triggers Human-in-the-Loop review."
        )
        result["forensic_rationale"] = f"{spread_msg}\n{existing_rat}".strip()
        result.setdefault("defect_codes", []).append("ERR_SAMPLE_SPREAD_EXCEEDED")

    return result
