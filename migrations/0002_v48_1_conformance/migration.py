def rollback(database: Path, package_root: Path) -> dict[str, Any]:
    baseline = package_root.resolve() / "rollback" / "baseline" / "nee_graph_v48.0.sqlite"
    if sha256_file(baseline) != BASELINE_DB_SHA256:
        raise AssertionError("packaged V48.0 rollback database hash mismatch")
    temp = database.with_suffix(database.suffix + ".rollback.tmp")
    shutil.copy2(baseline, temp)
    if sha256_file(temp) != BASELINE_DB_SHA256:
        temp.unlink(missing_ok=True)
        raise AssertionError("rollback copy hash mismatch")
    os.replace(temp, database)
    return {"result": "PASS", "database_sha256": sha256_file(database), "restored_version": "48.0"}
